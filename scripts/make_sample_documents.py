#!/usr/bin/env python3
"""Draw four obviously synthetic documents for testing the document reader.

    python scripts/make_sample_documents.py          # writes data/sample_documents/*.png

Real certificates carry real people's Aadhaar numbers, caste and income, so they never go
in a repository or a demo. These are drawn from scratch for one fictional person, carry a
SPECIMEN watermark across the page, name no issuing authority, and use no emblem. They
exist to exercise the pipeline end to end, including one deliberate trap: the income
certificate says Rs 72,000 a year, so a citizen who said "month-ku 3000" in the chat
(Rs 36,000 a year) is shown a conflict instead of having their answer silently replaced.
"""

from __future__ import annotations

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

OUT = Path(__file__).resolve().parent.parent / "data" / "sample_documents"
PERSON = "Lakshmi Selvam (fictional)"

DOCUMENTS = {
    "ration_card": ("FAMILY CARD", [
        ("Head of family", PERSON),
        ("Card category", "PHH - Priority Household (Rice)"),
        ("Number of members", "4"),
        ("District", "Madurai"),
        ("Card number", "3301 2299 8765 4321"),
    ]),
    "income_certificate": ("INCOME CERTIFICATE", [
        ("Name", PERSON),
        ("Address", "12 Example Street, Madurai District"),
        ("Annual family income", "Rs. 72,000 (Seventy two thousand) per annum"),
        ("Certificate number", "IC-0000-5521"),
        ("Date of issue", "14-03-2026"),
    ]),
    "community_certificate": ("COMMUNITY CERTIFICATE", [
        ("Name", PERSON),
        ("Community", "Adi Dravidar"),
        ("Category", "Scheduled Caste (SC)"),
        ("Religion", "Hindu"),
        ("District", "Madurai"),
    ]),
    "bank_passbook": ("SAVINGS ACCOUNT PASSBOOK", [
        ("Account holder", PERSON),
        ("Bank", "Example Co-operative Bank (fictional)"),
        ("Account number", "0001 2345 6789"),
        ("Branch", "Madurai Main"),
        ("Account type", "Savings"),
    ]),
}


def font(size: int) -> ImageFont.FreeTypeFont:
    for path in ("/System/Library/Fonts/Supplemental/Arial.ttf",
                 "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"):
        if Path(path).exists():
            return ImageFont.truetype(path, size)
    return ImageFont.load_default(size=size)


def draw(title: str, rows: list[tuple[str, str]]) -> Image.Image:
    width, height = 1400, 900
    page = Image.new("RGB", (width, height), (250, 247, 238))
    ink = ImageDraw.Draw(page)
    ink.rectangle([30, 30, width - 30, height - 30], outline=(60, 60, 60), width=4)
    ink.text((70, 60), "SAMPLE FOR SOFTWARE TESTING", font=font(26), fill=(150, 30, 30))
    ink.text((70, 110), title, font=font(54), fill=(20, 20, 20))
    y = 230
    for label, value in rows:
        ink.text((70, y), f"{label}:", font=font(34), fill=(70, 70, 70))
        ink.text((520, y), value, font=font(34), fill=(10, 10, 10))
        y += 90
    ink.text((70, height - 90),
             "Synthetic document generated by tn-schemematch. Not a real record.",
             font=font(26), fill=(150, 30, 30))

    # The watermark goes on its own layer so it can be rotated across the whole page.
    stamp = Image.new("RGBA", (width, height), (0, 0, 0, 0))
    ImageDraw.Draw(stamp).text((210, 400), "SPECIMEN - SYNTHETIC TEST DOCUMENT",
                               font=font(50), fill=(200, 40, 40, 70))
    stamp = stamp.rotate(18, center=(width / 2, height / 2))
    return Image.alpha_composite(page.convert("RGBA"), stamp).convert("RGB")


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    for name, (title, rows) in DOCUMENTS.items():
        path = OUT / f"{name}.png"
        draw(title, rows).save(path, optimize=True)
        print(f"wrote {path.relative_to(OUT.parent.parent)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
